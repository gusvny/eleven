"""t261008-50 — scenario run output must never dirty the tree (UT).

Defect: files regenerated by every suite run (integration/<ticket>/{shots,out,
evidence}/) were tracked, so "run the tests" left main's worktree dirty and the
merge gate's main-untouched check blocked every other lane (261008 pile-up).

Faces:
  A dirty-tree simulation — fresh run-output files keep `git status --porcelain` clean.
  B rule-drift lock     — .gitignore carries the exact run-output rules (and the
                          retired extension-scoped shots rule stays retired).
  C ignore face         — git check-ignore accepts run-output probes (incl. a
                          space-in-name path) and leaves the two carrier
                          deliverable directories un-ignored.
  E tracked-set face    — git ls-files holds no tracked file under shots/ or
                          out/, and tracked evidence/ files are only the two
                          carrier directories. Red until the worker's
                          `git rm -r --cached integration/t261008-36/evidence`
                          lands (intentional TDD ordering, review-sanctioned).
  D fail-closed face    — a non-git root is a named failure, never a silent skip.

Offline seconds, stdlib only, zero docker/browser, never touches 3099. git is
invoked read-only (status / ls-files / check-ignore); no index mutation.
"""
import shutil
import subprocess
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[2]
PROBE_TICKET = "t261008-50-selftest-probe"
PROBE_DIR = REPO_ROOT / "integration" / PROBE_TICKET
# Run-output dirs sit directly under integration/<ticket>/. These two hold
# hand-preserved quarantined deliverables, not run output (see their README).
CARRIER_EVIDENCE = (
    "integration/t261004-25/evidence/",
    "integration/t261004-28/evidence/",
)
RUN_OUTPUT_SEGMENTS = ("shots", "out", "evidence")
EXPECTED_RULES = (
    "integration/*/shots/",
    "integration/*/out/",
    "integration/*/evidence/*",
    "!integration/t261004-25/evidence/*",
    "!integration/t261004-28/evidence/*",
)
RETIRED_RULE = "integration/*/shots/*.png"


class CleanTreeError(AssertionError):
    """Named failure for a missing/unknown git root — never a silent skip."""


def _discover_root(start: Path) -> Path:
    """Walk up from `start` to the enclosing git work tree root."""
    cur = start.resolve()
    for cand in (cur, *cur.parents):
        if (cand / ".git").exists():
            return cand
    raise CleanTreeError(
        f"no enclosing git work tree found above {start} — "
        "the clean-tree check refuses to guess a root"
    )


def _git(root: Path, *args: str) -> "tuple[int, str]":
    try:
        proc = subprocess.run(
            ["git", "-C", str(root), *args],
            capture_output=True,
            text=True,
            timeout=30,
        )
    except FileNotFoundError:
        raise CleanTreeError("git executable not found — cannot run the clean-tree check")
    return proc.returncode, proc.stdout


def _tracked_files(root: Path) -> list[str]:
    rc, out = _git(root, "ls-files", "-z")
    assert rc == 0, f"git ls-files failed (rc={rc})"
    # NUL-delimited: paths with spaces/quotes survive verbatim.
    return [p for p in out.split("\x00") if p]


def _run_output_violations(paths: list[str]) -> list[str]:
    bad = []
    for p in paths:
        parts = p.split("/")
        if len(parts) < 3 or parts[0] != "integration":
            continue
        if parts[2] in RUN_OUTPUT_SEGMENTS and not p.startswith(CARRIER_EVIDENCE):
            bad.append(p)
    return sorted(bad)


# ---------- A: dirty-tree simulation ----------


def test_fresh_run_output_keeps_status_clean(tmp_path):
    root = _discover_root(Path(__file__))
    probe_rel = f"integration/{PROBE_TICKET}"
    probes = [
        f"{probe_rel}/shots/a.png",
        f"{probe_rel}/out/shot light.png",  # space in name
        f"{probe_rel}/evidence/receipt.txt",
    ]
    try:
        for rel in probes:
            f = root / rel
            f.parent.mkdir(parents=True, exist_ok=True)
            f.write_bytes(b"probe")
        rc, out = _git(root, "status", "--porcelain", "--", probe_rel)
        assert rc == 0, f"git status failed (rc={rc})"
        assert out == "", (
            "fresh run-output files dirtied the tree — the exact 261008 "
            f"defect shape:\n{out}"
        )
    finally:
        shutil.rmtree(PROBE_DIR, ignore_errors=True)
        # If the tree was still dirty here, face E / the gate catches it later;
        # the probe dir itself must never linger.
        assert not PROBE_DIR.exists(), "selftest probe dir not reaped"


# ---------- B: rule-drift lock ----------


def test_gitignore_carries_run_output_rules():
    gi = REPO_ROOT / ".gitignore"
    assert gi.is_file(), ".gitignore missing at repo root — nothing enforces the contract"
    text = gi.read_text(encoding="utf-8")
    # Judge ACTIVE rule lines only: prose that mentions a retired rule inside a
    # comment must not read as the rule being back.
    active = [ln.strip() for ln in text.splitlines() if ln.strip() and not ln.lstrip().startswith("#")]
    missing = [r for r in EXPECTED_RULES if r not in active]
    assert not missing, f".gitignore lost run-output rules: {missing}"
    assert RETIRED_RULE not in active, (
        "the retired extension-scoped rule 'integration/*/shots/*.png' is back — "
        "directory-level coverage (non-png strays count) was the point of t261008-50"
    )


# ---------- C: ignore face, incl. the carrier carve-out ----------


def test_check_ignore_accepts_run_output_and_spares_carriers():
    root = _discover_root(Path(__file__))
    ignored = [
        "integration/t261008-50-selftest/shots/a.png",
        "integration/t261008-50-selftest/out/a b.png",
        "integration/t261008-50-selftest/evidence/a.txt",
    ]
    for rel in ignored:
        rc, out = _git(root, "check-ignore", "--", rel)
        assert rc == 0, f"{rel} is NOT ignored (rc={rc}) — run output would dirty the tree"
    for rel in ("integration/t261004-25/evidence/README.md",
                "integration/t261004-28/evidence/t261004-19_source_order_lock.py.txt"):
        rc, _ = _git(root, "check-ignore", "--", rel)
        assert rc != 0, f"carrier deliverable {rel} is ignored — future files there would be silently dropped"


# ---------- E: tracked-set face (the worker's rm is what turns this green) ----------


def test_no_tracked_run_output_outside_carriers():
    bad = _run_output_violations(_tracked_files(_discover_root(Path(__file__))))
    assert not bad, (
        "tracked scenario run output still in the index (untrack with "
        "`git rm -r --cached <path>`; files stay on disk): " + ", ".join(bad)
    )


def test_tracked_carriers_survive():
    root = _discover_root(Path(__file__))
    tracked = _tracked_files(root)
    for carrier_rel in CARRIER_EVIDENCE:
        hits = [p for p in tracked if p.startswith(carrier_rel)]
        assert hits, f"carrier directory {carrier_rel} lost all tracked deliverables"


# ---------- D: fail-closed face ----------


def test_non_git_root_fails_named(tmp_path):
    with pytest.raises(CleanTreeError, match="no enclosing git work tree"):
        _discover_root(tmp_path)


def test_missing_git_binary_fails_named():
    import unittest.mock as mock

    with mock.patch("subprocess.run", side_effect=FileNotFoundError("git")):
        with pytest.raises(CleanTreeError, match="git executable not found"):
            _git(REPO_ROOT, "ls-files")
