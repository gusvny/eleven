/**
 * lib_degrade_matrix.mjs — the "feed it bad data and make it speak" template.
 *
 * WHY THIS EXISTS (261026). Four host-reported defects on one night were not wrong code, they were
 * a READER disagreeing with a WRITER: the panel expected a daily opened/closed series and the API
 * sent a blocked leaderboard (empty chart); the tab thought the declared instances were five and
 * the archive handed it forty shard filenames (every row "decl-unreadable"/"not_run"); the token
 * tile headlined cache-inclusive traffic and its sub-line the fresh part (two calibers on one card);
 * every epic activity landed in the year 2001 (a display string handed to `new Date()`).
 *
 * None of those is catchable by looking at code shape. All four ARE catchable by feeding a read
 * face the five shapes below and asking what it says.
 *
 * THE CONTRACT (one rule, no shape matching):
 *
 *   A read face may return a PLACEHOLDER (a dash, a zero, an empty list, a "not run") ONLY together
 *   with a non-empty reason that a person can act on. The one exception is the face's own healthy
 *   state: a real payload renders the expected fields and needs no reason.
 *
 *   And the fifth shape is the one that catches caliber drift: the PRODUCER'S REAL PAYLOAD must
 *   render what the face promises. A hand-written stub proves nothing — it was written by the same
 *   mind that wrote the reader.
 *
 * HOW TO USE
 *
 *   1. Take the real read face (a pure function imported from the host module, never a copy).
 *   2. Declare its promised fields: `expect: (out) => [...]` — what a healthy payload must render.
 *   3. Pass a `real` payload captured from the producer (a file under fixtures/, regenerated by the
 *      producer's own script when the contract changes; the fixture freshness is checked by the
 *      scenario that owns it).
 *   4. `record` each case; the module prints a SUMMARY in the suite's own vocabulary.
 *
 *   import { runDegradeMatrix, shapes } from '../../lib_degrade_matrix.mjs'
 *   const r = runDegradeMatrix({
 *     face: 'inspection-coverage',                     // the face being judged
 *     call: (payload) => buildCoverageCore(payload.periods, payload.instances, payload.attempts, TABLES),
 *     real: realPayload,                                // the producer's own output
 *     expect: (out) => ({ rows: out.rows.length > 0 }),
 *     copiesKey: 'copy',                                // which field carries the human sentence
 *   })
 *   process.exit(r.ok ? 0 : 1)
 *
 * NO DEPENDENCIES, NO NETWORK, NO BROWSER: this template only calls the face and reads its answer.
 */

/** The five shapes every read face must survive. Order matters for the report. */
export const SHAPES = ['missing', 'unreadable', 'empty', 'garbage', 'real']

/** What "missing" means per face is the caller's business, but the four broken shapes are fixed. */
export function shapePayloads(real) {
  return {
    missing: null,
    unreadable: 'UNREADABLE',           // a sentinel the adapter maps to its "file exists, cannot read" branch
    empty: undefined,
    garbage: { garbage: true, periods: 'not-an-array', reports: 42, instances: 7 },
    real,
  }
}

/** A placeholder is anything a person would read as "no data": a dash, a zero, an empty array. */
export function looksLikePlaceholder(value) {
  if (value === null || value === undefined) return true
  if (typeof value === 'string') {
    const s = value.trim()
    return s === '' || s === '—' || s === '-' || s === 'n/a' || s === 'N/A'
  }
  if (typeof value === 'number') return value === 0
  if (Array.isArray(value)) return value.length === 0
  return false
}

/** Every string in an answer-shaped object, for the "does it name a reason" question. */
function stringsOf(value, out = [], depth = 0) {
  if (depth > 6 || value === null || value === undefined) return out
  if (typeof value === 'string') { out.push(value); return out }
  if (Array.isArray(value)) { for (const v of value) stringsOf(v, out, depth + 1); return out }
  if (typeof value === 'object') { for (const v of Object.values(value)) stringsOf(v, out, depth + 1) }
  return out
}

/** A reason is a sentence with words in it — not a marker, not our own placeholder token. */
export function namesAReason(answer, copiesKey = 'reason') {
  const candidates = []
  if (answer && typeof answer === 'object' && !Array.isArray(answer)) {
    for (const key of [copiesKey, 'reason', 'note', 'why', 'error', 'blocked_reason', 'sub']) {
      const v = answer[key]
      if (typeof v === 'string') candidates.push(v)
    }
  }
  if (candidates.length === 0) candidates.push(...stringsOf(answer))
  return candidates.some((s) => {
    const t = String(s).trim()
    if (t.length < 12) return false                 // "—" / "n/a" / "error" are markers, not reasons
    if (looksLikePlaceholder(t)) return false
    return /[a-z]/i.test(t) && /\s/.test(t)          // a sentence, not a token
  })
}

/**
 * Run the matrix. Returns { ok, cases, summary } and never throws on a face failure (a throw is a
 * case: "the face crashed on the <shape> payload", which is exactly what a bare traceback is).
 */
export function runDegradeMatrix({ face, call, real, expect, copiesKey = 'reason', log = true }) {
  const payloads = shapePayloads(real)
  const cases = []
  const push = (name, okCase, detail) => {
    cases.push({ name, ok: okCase, detail })
    if (log) console.log(`${okCase ? 'ok  ' : 'FAIL'} ${face}/${name}${detail ? ' — ' + detail : ''}`)
  }

  for (const shape of SHAPES) {
    let answer
    try {
      answer = call(payloads[shape])
    } catch (e) {
      // A crash IS the finding: the face never gets to speak.
      push(`${shape}-no-throw`, false, `threw ${e && e.message ? e.message : String(e)}`)
      continue
    }
    push(`${shape}-no-throw`, true, '')
    if (shape === 'real') {
      const want = (typeof expect === 'function' ? expect(answer) : {}) || {}
      for (const [field, okField] of Object.entries(want)) {
        push(`real-renders-${field}`, okField === true, okField === true ? '' : `the producer's own payload did not render ${field}`)
      }
      continue
    }
    // The four broken shapes must SAY something, and it must be a reason, not a dash.
    push(`${shape}-names-reason`, namesAReason(answer, copiesKey),
      namesAReason(answer, copiesKey) ? '' : `answer carries no usable reason: ${JSON.stringify(answer).slice(0, 160)}`)
  }

  const failed = cases.filter((c) => !c.ok)
  const summary = `ran=${cases.length} pass=${cases.length - failed.length} fail=${failed.length}`
  if (log) console.log(`SUMMARY ${summary} (degrade matrix: ${face})`)
  return { ok: failed.length === 0, cases, summary }
}
